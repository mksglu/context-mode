// T-CMP arms (DECISIONS-r9 §V T-CMP, plan.md §2 E3, ADR-0009 §6, DECISIONS-r6 D6).
// One temp project per arm. What the model sees after the reset turn:
//   (a) CC compact summary + D6 pointer line: release-out plugin as built, unchanged (the thing under test)
//   (b) CC compact summary + 2 KB block       (c) CC compact summary only
//   (d) 2 KB block only (models a "none" host) (e) pointer line only, on a no-summary condition
// Arms b-e load the same release-out server and hook bundle; only SessionStart goes through a small
// arm hook that delivers the arm's text instead. The block text is the release-out server's own
// ctx_resume() reply, read through e2e/harness/mcp-client.mjs. No import of src/ (GS4).
// No-summary arms (d, e) reset with "/clear" instead of "/compact": the host then keeps no history and
// writes no summary, so only the injected text carries the earlier work (commit body DEVIATION row).
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const RUNS_PER_ARM = 10; // DECISIONS-r9 T-CMP: 10 per arm (a)-(e)
export const PLUGIN_NAME = "context-mode";
export const TOOL_PREFIX = "mcp__plugin_context-mode_context-mode__";
// Byte copy of COMPACT_POINTER_LINE (DECISIONS-r6 D6, ADR-0009 §6); e2e/ cannot import src/.
export const POINTER_LINE =
  'context-mode: earlier work of this session is in ctx_resume (state block) and ctx_search(scope:"session", sort:"timeline").';

const arm = (id, pointer, block, summary, label) =>
  Object.freeze({ id, pointer, block, summary, runs: RUNS_PER_ARM, reset: summary ? "/compact" : "/clear", label });

export const ARMS = Object.freeze({
  a: arm("a", true, false, true, "CC summary + D6 pointer (release-out as built)"),
  b: arm("b", false, true, true, "CC summary + 2 KB block"),
  c: arm("c", false, false, true, "CC summary only"),
  d: arm("d", false, true, false, "2 KB block only (none host)"),
  e: arm("e", true, false, false, "pointer line only, no summary"),
});
export const ARM_IDS = Object.freeze(Object.keys(ARMS));

const MCP_CLIENT_URL = pathToFileURL(fileURLToPath(new URL("../../harness/mcp-client.mjs", import.meta.url))).href;
const ALLOWED_TOOLS = ["ctx_resume", "ctx_search"].map((t) => TOOL_PREFIX + t);

/** Argv for runSession: built-in tools off, the ctx read tools allowed, one plugin dir. */
function argsFor(pluginDir) {
  return ["--plugin-dir", pluginDir, "--tools", "", "--allowedTools", ...ALLOWED_TOOLS];
}

/**
 * The SessionStart hook of arms b-e. On the arm's reset source it prints the arm's text as
 * additionalContext; on any other source it hands the payload to the release-out hook unchanged.
 */
function armHookSource(a, releaseOut, stateFile) {
  const resetSource = a.summary ? "compact" : "clear";
  return `// generated by e2e/live/compact/arms.mjs for T-CMP arm ${a.id}
import { spawn } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { spawnBundle } from ${JSON.stringify(MCP_CLIENT_URL)};

const RELEASE_OUT = ${JSON.stringify(releaseOut)};
const STATE_FILE = ${JSON.stringify(stateFile)};
const POINTER_LINE = ${JSON.stringify(POINTER_LINE)};
const WANT = ${JSON.stringify({ pointer: a.pointer, block: a.block, resetSource, keepSession: !a.summary })};
const INIT = { protocolVersion: "2024-11-05", capabilities: {}, clientInfo: { name: "t-cmp-arm-${a.id}", version: "0" } };

const chunks = [];
for await (const c of process.stdin) chunks.push(c);
const raw = Buffer.concat(chunks).toString("utf8");
const p = JSON.parse(raw);

if (p.source !== WANT.resetSource) {
  if (p.source === "startup") writeFileSync(STATE_FILE, String(p.session_id ?? ""));
  const child = spawn(process.execPath, [RELEASE_OUT + "/hook.mjs", "--agent", "claude-code"], { stdio: ["pipe", "inherit", "inherit"] });
  child.stdin.end(raw);
  child.on("exit", (code) => { process.exitCode = code ?? 1; });
} else {
  // "/clear" starts a new session id; the block is the earlier session's, saved at startup.
  const sid = WANT.keepSession ? readFileSync(STATE_FILE, "utf8") : String(p.session_id ?? "");
  const parts = [];
  if (WANT.block) {
    const c = spawnBundle(RELEASE_OUT + "/server.mjs", process.env, ["--agent", "claude-code"]);
    try {
      await c.request("initialize", INIT);
      c.notify("notifications/initialized");
      const r = await c.request("tools/call", { name: "ctx_resume", arguments: { session: sid } });
      parts.push(r.content[0].text);
      await c.close();
    } finally {
      c.kill();
    }
  }
  if (WANT.pointer) parts.push(POINTER_LINE);
  if (parts.length > 0) {
    process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: "SessionStart", additionalContext: parts.join("\\n") } }));
  }
}
`;
}

/** Plugin dir for arms b-e: release-out server and hooks by absolute path; SessionStart through the arm hook. */
function writeArmPlugin(a, releaseOut, dir) {
  const pluginDir = path.join(dir, "plugin");
  mkdirSync(path.join(pluginDir, ".claude-plugin"), { recursive: true });
  mkdirSync(path.join(pluginDir, "hooks"), { recursive: true });
  const release = JSON.parse(readFileSync(path.join(releaseOut, ".claude-plugin", "plugin.json"), "utf8"));
  const server = release.mcpServers[PLUGIN_NAME];
  const manifest = {
    name: PLUGIN_NAME,
    version: release.version,
    hooks: "./hooks/hooks.json",
    mcpServers: { [PLUGIN_NAME]: { ...server, args: server.args.map((x) => x.split("${CLAUDE_PLUGIN_ROOT}").join(releaseOut)) } },
  };
  writeFileSync(path.join(pluginDir, ".claude-plugin", "plugin.json"), JSON.stringify(manifest, null, 2));

  const hookFile = path.join(pluginDir, "arm-hook.mjs");
  writeFileSync(hookFile, armHookSource(a, releaseOut, path.join(dir, "first-session-id")));
  const hooks = JSON.parse(readFileSync(path.join(releaseOut, "hooks", "claude-code.json"), "utf8"));
  for (const [event, entries] of Object.entries(hooks.hooks)) {
    for (const entry of entries) {
      for (const h of entry.hooks) {
        h.command = event === "SessionStart" ? `node ${JSON.stringify(hookFile)}` : h.command.split("${CLAUDE_PLUGIN_ROOT}").join(releaseOut);
      }
    }
  }
  writeFileSync(path.join(pluginDir, "hooks", "hooks.json"), JSON.stringify(hooks, null, 2));
  return pluginDir;
}

/**
 * Sets up one arm in a fresh temp dir under `root`.
 * @param {string} id - "a".."e"
 * @param {{ releaseOut: string, root: string }} o - absolute release-out dir (built, unchanged) and a scratch root
 * @returns {{ arm: object, dir: string, cwd: string, pluginDir: string, args: string[], reset: string, cleanup: () => void }}
 *   `cwd` is the arm's temp project; `args` go to runSession; `reset` is the turn that replaces history.
 */
export function setupArm(id, o) {
  const a = ARMS[id];
  if (a === undefined) throw new Error(`arms: unknown arm ${id}`);
  const releaseOut = path.resolve(o.releaseOut);
  mkdirSync(o.root, { recursive: true });
  const dir = mkdtempSync(path.join(o.root, `arm-${id}-`));
  const cwd = path.join(dir, "project");
  mkdirSync(cwd);
  // context-mode resolves the project from a git repository (PRD §5); the temp project is one.
  const g = spawnSync("git", ["init", "-q", cwd], { encoding: "utf8" });
  if (g.status !== 0) throw new Error(`arms: git init failed: ${g.stderr}`);
  const pluginDir = id === "a" ? releaseOut : writeArmPlugin(a, releaseOut, dir);
  return { arm: a, dir, cwd, pluginDir, args: argsFor(pluginDir), reset: a.reset, cleanup: () => rmSync(dir, { recursive: true, force: true }) };
}
